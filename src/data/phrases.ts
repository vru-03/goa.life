export const getKonkaniPhraseForNow = (): KonkaniPhrase => {
  const hour = new Date().getHours();
  let timeCategory: 'morning' | 'afternoon' | 'evening' | 'night';

  if (hour >= 5 && hour < 12) {
    timeCategory = 'morning';
  } else if (hour >= 12 && hour < 17) {
    timeCategory = 'afternoon';
  } else if (hour >= 17 && hour < 21) {
    timeCategory = 'evening';
  } else {
    timeCategory = 'night';
  }

  const matching = KONKANI_PHRASES.filter(
    (p) => p.timeOfDay === timeCategory || p.timeOfDay === 'all-day'
  );

  // Return consistent phrase for the current hour index or random
  const index = hour % matching.length;
  return matching[index] || KONKANI_PHRASES[0];
};
